/**
 * Build Appendix 16C maritime location code map from HMRC mirror PSV.
 * Run: node scripts/build-appendix-16c-codes.mjs
 */
const fs = require("fs");
const path = require("path");

const SRC = path.join(process.cwd(), "spec/hmrc-mirror/appendix-16c-maritime.psv");
const OUT = path.join(process.cwd(), "src/lib/generated/appendix-16c-codes.ts");

const lines = fs.readFileSync(SRC, "utf8").split(/\r?\n/);
const codes = new Map();

for (const line of lines) {
  if (!line.trim()) continue;
  const parts = line.split("|").map((p) => p.trim());
  if (parts[0] === "Name" || parts.includes("Location Code")) continue;

  const code = parts.find((p) => /^GB[A-Z0-9]{8,35}$/.test(p));
  if (!code) continue;

  const name = parts[0] || code;
  if (!codes.has(code)) {
    codes.set(code, name.replace(/"/g, '\\"'));
  }
}

const entries = [...codes.entries()].sort(([a], [b]) => a.localeCompare(b));
const body = entries.map(([code, name]) => `  ${JSON.stringify(code)}: ${JSON.stringify(name)},`).join("\n");

const output = `/** Generated by scripts/build-appendix-16c-codes.mjs — do not edit manually. */
export const APPENDIX_16C_MARITIME_CODES: Readonly<Record<string, string>> = {
${body}
} as const;

export const APPENDIX_16C_CODE_LIST = Object.keys(APPENDIX_16C_MARITIME_CODES);
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, output);
console.log(`Wrote ${entries.length} codes to ${OUT}`);
